"""主要指数静态表。

为什么用手工维护的静态表，而不是拉全市场指数列表：
  1. 东财的指数列表接口（`stock_zh_index_spot_em`）在服务器 IP 上会被限流，不稳定；
  2. 用户真正关心的指数就是主流宽基 + 行业主题这二十来个，静态表更稳、更快、可读。

代码格式与个股保持一致（6 位数字 + `.SH`/`.SZ`），这样可以复用同一套
代码解析、缓存文件命名与回测链路，不需要为指数单开一条数据通道。
"""

